#!/usr/bin/env bash
# Regenerates migrations/0001_baseline.sql from the v0NN_*.sql files it replaces.
#
#   scripts/baseline.sh <dir of v0NN_*.sql> <postgres maintenance url>
#
# Applies every file in name order to a scratch database, dumps schema and seed
# rows, and strips what sqlx cannot run: psql meta-commands, session SETs,
# extension comments. Only while no database has recorded the baseline: its
# checksum is stored on adoption, so a later change is a new migration.
set -euo pipefail

src=${1:?dir of v0NN_*.sql}
admin=${2:?postgres maintenance url}
out="$(cd "$(dirname "$0")/.." && pwd)/migrations/0001_baseline.sql"
scratch="myrtle_baseline_$$"
url="${admin%/*}/$scratch"

psql -qX "$admin" -c "CREATE DATABASE $scratch"
trap 'psql -qX "$admin" -c "DROP DATABASE IF EXISTS $scratch"' EXIT

psql -qX -v ON_ERROR_STOP=1 "$url" -c \
  "CREATE TABLE _migrations (name VARCHAR(100) PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW())"

strip='^\\(un)?restrict |^SET |^SELECT pg_catalog\.set_config\(|^COMMENT ON EXTENSION |^-- Dumped (from|by) '
if grep -nE "^SET |^SELECT pg_catalog\.set_config\(" "$src"/v0*.sql; then
  echo "a source line the dump filter would delete from a function body" >&2
  exit 1
fi

names=()
for f in "$src"/v0*.sql; do
  name=$(basename "$f" .sql)
  psql -qX -v ON_ERROR_STOP=1 -1 -f "$f" "$url" >/dev/null
  names+=("$name")
done

{
  echo "-- Schema and seed rows of ${names[0]}..${names[${#names[@]}-1]}, generated by scripts/baseline.sh."
  echo "-- A database that already ran those is adopted without executing this file."
  echo
  echo "SET LOCAL check_function_bodies = false;"
  pg_dump --schema-only --no-owner --no-privileges "$url" | grep -vE "$strip" | cat -s
  pg_dump --data-only --column-inserts --exclude-table=_migrations "$url" | grep -vE "$strip" | cat -s
  echo
  echo "INSERT INTO public._migrations (name) VALUES"
  for i in "${!names[@]}"; do
    sep=,
    [ "$i" -eq $((${#names[@]} - 1)) ] && sep=';'
    echo "    ('${names[$i]}')$sep"
  done
} >"$out"

echo "wrote $out ($(wc -l <"$out" | tr -d ' ') lines, ${#names[@]} legacy migrations)"
