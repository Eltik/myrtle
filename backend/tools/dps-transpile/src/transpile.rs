pub fn normalize_heal_variables(py_body: &str) -> String {
    let mut s = py_body.to_string();
    s = s.replace("skillhps", "skill_hps");
    s = s.replace("avghps", "avg_hps");
    s = s.replace("skilldown_hps", "base_hps");
    s
}

pub fn transpile_all(
    mode: Mode,
    py_src: &str,
    formulas: &HashMap<String, OperatorFormula>,
) -> anyhow::Result<()> {
    println!(
        "\n=== Transpiling Python -> Rust ({}) ===",
        mode.human_label()
    );

    let mut custom_ops: Vec<(&str, &str, &OperatorFormula)> = Vec::new();
    for (char_id, formula) in formulas {
        custom_ops.push((char_id.as_str(), formula.class_name.as_str(), formula));
    }
    custom_ops.sort_by_key(|&(_, name, _)| name);

    println!("Found {} operators", custom_ops.len());

    let class_re = Regex::new(&format!(
        r"class\s+(\w+)\s*\(\s*{}\s*\)\s*:",
        mode.class_base_alt()
    ))
    .unwrap();
    let class_positions: Vec<(usize, String)> = class_re
        .captures_iter(py_src)
        .map(|cap| (cap.get(0).unwrap().start(), cap[1].to_string()))
        .collect();

    let mut class_bodies: HashMap<String, String> = HashMap::new();
    for (i, (start, name)) in class_positions.iter().enumerate() {
        let end = class_positions
            .get(i + 1)
            .map_or(py_src.len(), |(pos, _)| *pos);
        class_bodies.insert(name.clone(), py_src[*start..end].to_string());
    }

    let shape = mode.output_shape();
    let (header_blurb, return_type, fn_signature_suffix) = match shape {
        OutputShape::F64Dps => (
            "//! Auto-generated custom DPS implementations.\n",
            "Option<f64>",
            "unit: &OperatorUnit, enemy: &EnemyStats",
        ),
        OutputShape::HpsTriple => (
            "//! Auto-generated custom HPS implementations.\n",
            "Option<HpsResult>",
            "unit: &OperatorUnit, enemy: &EnemyStats",
        ),
    };
    let use_stmt = match shape {
        OutputShape::F64Dps => "use super::super::operator_unit::{EnemyStats, OperatorUnit};\n\n",
        OutputShape::HpsTriple => {
            "use super::super::HpsResult;\nuse super::super::operator_unit::{EnemyStats, OperatorUnit};\n\n"
        }
    };

    let mut generated = String::new();
    generated.push_str(header_blurb);
    generated.push_str("//! Generated by `cargo run -p myrtle-dps-transpile`\n");
    generated.push_str("//! DO NOT EDIT MANUALLY.\n\n");
    generated.push_str("#![allow(unused_variables, unused_mut, unused_assignments, unused_parens, unreachable_code, path_statements, unused_must_use, non_snake_case, clippy::all, clippy::pedantic, clippy::nursery)]\n\n");
    generated.push_str(use_stmt);

    let mut dispatch_arms: Vec<(String, String)> = Vec::new();
    let mut duration_arms: Vec<(String, String)> = Vec::new();
    let mut success = 0;
    let mut failed = 0;

    for (char_id, class_name, _formula) in &custom_ops {
        let Some(class_body) = class_bodies.get(*class_name) else {
            eprintln!("  SKIP: {class_name} - not found in Python source");
            failed += 1;
            continue;
        };

        let mut method_body = String::new();
        for method in mode.method_names() {
            let body = extract_method(class_body, method);
            if !body.trim().is_empty() {
                method_body = body;
                break;
            }
        }
        if method_body.trim().is_empty() {
            eprintln!(
                "  SKIP: {class_name} - no {} method",
                mode.method_names().join(" or ")
            );
            failed += 1;
            continue;
        }

        if shape == OutputShape::HpsTriple {
            method_body = normalize_heal_variables(&method_body);
        }

        let init_state = analyze_init_state(class_name, class_body, &method_body);
        let collisions = find_local_self_collisions(
            class_name,
            &method_body,
            &collision_candidates(&init_state),
        );
        for c in collisions.iter().filter(|c| c.self_assigned) {
            eprintln!(
                "  LOCAL/SELF NAME NOT SPLIT: {class_name}.{} (body rebinds self.{} too)",
                c.name, c.name
            );
        }
        method_body = split_local_self_collisions(&method_body, &collisions);
        for f in &init_state.findings {
            if let InitStateKind::Unhandled(why) = &f.kind {
                eprintln!(
                    "  INIT STATE NOT REPRODUCED: {class_name}.{} ({why}): {}",
                    f.field, f.line
                );
            }
        }
        for field in &init_state.free_fields {
            method_body = Regex::new(&format!(r"self\.{field}\b"))
                .unwrap()
                .replace_all(&method_body, format!("{FREE_FIELD_PREFIX}{field}").as_str())
                .to_string();
        }
        if !init_state.prelude.is_empty() {
            method_body = format!("{}\n{method_body}", init_state.prelude.join("\n"));
        }
        let rust_fn_name = to_snake_case(class_name);
        let rust_body = transpile_skill_dps(&method_body, &init_state, shape);

        let fn_start_pos = generated.len();
        generated.push_str(&format!(
            "/// {class_name} - auto-transpiled from Python\npub fn {rust_fn_name}({fn_signature_suffix}) -> {return_type} {{\n"
        ));
        generated.push_str(&rust_body);
        generated.push_str("}\n\n");

        let fn_body_check = &generated[fn_start_pos..];
        let hardcoded_fallbacks: &[&str] = match shape {
            OutputShape::F64Dps => &[],
            OutputShape::HpsTriple => HEAL_FALLBACKS,
        };

        let has_bad_syntax = hardcoded_fallbacks.contains(class_name)
            || fn_body_check.contains("= = ")
            || fn_body_check.contains("! = ");

        if has_bad_syntax {
            generated.truncate(fn_start_pos);
            let stub_return = match shape {
                OutputShape::F64Dps => "    None\n",
                OutputShape::HpsTriple => "    None\n",
            };
            generated.push_str(&format!(
                "/// {class_name} - fallback (transpiler limitation)\npub fn {rust_fn_name}({fn_signature_suffix}) -> {return_type} {{\n{stub_return}}}\n\n"
            ));
            eprintln!("  FALLBACK: {class_name} - syntax check failed");
        }

        let sets_duration = init_state
            .findings
            .iter()
            .any(|f| f.field == "skill_duration" && f.kind == InitStateKind::Hoisted);
        if sets_duration && !has_bad_syntax {
            let body = format!("{}\nreturn skill_duration", init_state.prelude.join("\n"));
            let rust = transpile_skill_dps(&body, &init_state, OutputShape::F64Dps);
            generated.push_str(&format!(
                "/// {class_name} - the skill duration its `__init__` sets\npub fn {rust_fn_name}_skill_duration(unit: &OperatorUnit, enemy: &EnemyStats) -> Option<f64> {{\n{rust}}}\n\n"
            ));
            duration_arms.push((
                char_id.to_string(),
                format!("{rust_fn_name}_skill_duration"),
            ));
        }

        dispatch_arms.push((char_id.to_string(), rust_fn_name));
        success += 1;
    }

    println!("Transpiled: {success}, Failed: {failed}");

    report_hand_overlap(mode, &dispatch_arms);
    if generated.contains("py_comb(") {
        generated.push_str(PY_COMB_FN);
    }

    let mut mod_rs = build_dispatch_mod(shape, mode.generated_mod_name(), &dispatch_arms);
    mod_rs.push_str(&build_duration_dispatch(
        mode.generated_mod_name(),
        &duration_arms,
    ));
    let generated = rustfmt(&generated, &mode.generated_rs_path())?;
    let mod_rs = rustfmt(&mod_rs, &mode.dispatch_rs_path())?;

    let generated_path = mode.generated_rs_path();
    write_output(&generated_path, generated.as_bytes())?;
    println!("Written to {}", generated_path.display());

    let dispatch_path = mode.dispatch_rs_path();
    write_output(&dispatch_path, mod_rs.as_bytes())?;
    println!(
        "Written to {} ({} dispatch arms)",
        dispatch_path.display(),
        dispatch_arms.len()
    );
    Ok(())
}

fn rustfmt(source: &str, target: &Path) -> anyhow::Result<String> {
    let mut child = match Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
    {
        Ok(child) => child,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            bail!("rustfmt not found on PATH; install it with `rustup component add rustfmt`")
        }
        Err(e) => return Err(e).context("start rustfmt"),
    };
    if let Some(stdin) = child.stdin.as_mut() {
        stdin
            .write_all(source.as_bytes())
            .context("write to rustfmt")?;
    }
    let output = child.wait_with_output().context("wait for rustfmt")?;
    if !output.status.success() {
        bail!(
            "rustfmt rejected the source for {}:\n{}",
            target.display(),
            String::from_utf8_lossy(&output.stderr)
        );
    }
    String::from_utf8(output.stdout).context("rustfmt output is not UTF-8")
}

fn build_duration_dispatch(generated_mod: &str, arms: &[(String, String)]) -> String {
    let mut out = String::new();
    out.push_str(
        "\n/// The skill duration the operator's Python `__init__` sets, when it sets one.\n",
    );
    out.push_str(
        "/// The engine uses it for the formula, total damage, average and cycle alike.\n",
    );
    out.push_str("pub fn dispatch_skill_duration(unit: &OperatorUnit) -> Option<f64> {\n");
    if arms.is_empty() {
        out.push_str("    let _ = unit;\n    None\n}\n");
        return out;
    }
    out.push_str(
        "    let enemy = EnemyStats {\n        defense: 0.0,\n        res: 0.0,\n    };\n",
    );
    out.push_str("    let op_id = unit.data.data.id.as_deref().unwrap_or(\"\");\n");
    out.push_str("    match op_id {\n");
    for (char_id, fn_name) in arms {
        out.push_str(&format!(
            "        \"{char_id}\" => {generated_mod}::{fn_name}(unit, &enemy),\n"
        ));
    }
    out.push_str("        _ => None,\n    }\n}\n");
    out
}

fn build_dispatch_mod(
    shape: OutputShape,
    generated_mod: &str,
    dispatch_arms: &[(String, String)],
) -> String {
    let mut out = String::new();
    out.push_str("//! Auto-generated dispatch table. DO NOT EDIT MANUALLY.\n");
    out.push_str(&format!(
        "//! Sibling of `{generated_mod}.rs` - both are declared by the hand-written `mod.rs`.\n\n"
    ));
    out.push_str("#![allow(clippy::all, clippy::pedantic, clippy::nursery)]\n\n");
    match shape {
        OutputShape::F64Dps => {
            out.push_str("use super::super::operator_unit::{EnemyStats, OperatorUnit};\n");
            out.push_str(&format!("use super::{generated_mod};\n\n"));
            out.push_str(
                "pub fn dispatch(unit: &OperatorUnit, enemy: &EnemyStats) -> Option<f64> {\n",
            );
            out.push_str("    let op_id = unit.data.data.id.as_deref().unwrap_or(\"\");\n");
            out.push_str("    match op_id {\n");
            for (char_id, fn_name) in dispatch_arms {
                out.push_str(&format!(
                    "        \"{char_id}\" => {generated_mod}::{fn_name}(unit, enemy),\n"
                ));
            }
            out.push_str("        _ => None,\n");
            out.push_str("    }\n");
            out.push_str("}\n");
        }
        OutputShape::HpsTriple => {
            out.push_str("use super::super::HpsResult;\n");
            out.push_str("use super::super::operator_unit::{EnemyStats, OperatorUnit};\n");
            out.push_str(&format!("use super::{generated_mod};\n\n"));
            out.push_str("/// Dispatch the operator's healing formula. Returns None when the\n");
            out.push_str("/// operator has no transpiled HPS implementation.\n");
            out.push_str("pub fn dispatch(unit: &OperatorUnit) -> Option<HpsResult> {\n");
            out.push_str("    // Most healers don't need enemy stats; pass a zero target so the\n");
            out.push_str(
                "    // generated functions' boilerplate `defense`/`res` locals stay 0.\n",
            );
            out.push_str("    let enemy = EnemyStats { defense: 0.0, res: 0.0 };\n");
            out.push_str("    let op_id = unit.data.data.id.as_deref().unwrap_or(\"\");\n");
            out.push_str("    match op_id {\n");
            for (char_id, fn_name) in dispatch_arms {
                out.push_str(&format!(
                    "        \"{char_id}\" => {generated_mod}::{fn_name}(unit, &enemy),\n"
                ));
            }
            out.push_str("        _ => None,\n");
            out.push_str("    }\n");
            out.push_str("}\n");
        }
    }
    out
}

